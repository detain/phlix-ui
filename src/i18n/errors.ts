/** The registry membership set — parse boundary for untrusted wire strings. */
const REGISTERED_ERROR_CODES: ReadonlySet<string> = new Set<string>(ERROR_CODES);

/** Is `value` an exact wire code from the contracts registry? */
export function isRegisteredErrorCode(value: unknown): value is ErrorCode {
  return typeof value === 'string' && REGISTERED_ERROR_CODES.has(value);
}

/** All complete catalogs, keyed by locale tag. */
export const ERROR_MESSAGES: Record<PhlixErrorLocale, PhlixErrorCatalog> = {
  en: EN,
  es: ES,
  fr: FR,
  de: DE,
  it: IT,
  pt_BR: PT_BR,
  ja: JA,
};

/** Resolve a (possibly untrusted) locale tag to a catalog key — anything else speaks 'en'. */
function resolveErrorLocale(locale: PhlixErrorLocale | null | undefined): PhlixErrorLocale {
  if (typeof locale === 'string' && locale in ERROR_MESSAGES) {
    return locale as PhlixErrorLocale;
  }
  return 'en';
}

/**
 * Localize a wire error code.
 *
 * Order: locale catalog → English catalog → caller `fallback` (typically the
 * server's debug text) → generic error label. Registered codes always resolve
 * from a catalog (completeness is compile-enforced), so the fallback path is
 * exactly the "unknown wire string" path. Never throws.
 */
export function errorCodeMessage(
  code: string | null | undefined,
  locale?: PhlixErrorLocale | null,
  fallback?: string | null,
): string {
  if (isRegisteredErrorCode(code)) {
    const localized = ERROR_MESSAGES[resolveErrorLocale(locale)][code];
    if (typeof localized === 'string' && localized !== '') return localized;
    const english = ERROR_MESSAGES.en[code];
    if (typeof english === 'string' && english !== '') return english;
  }
  if (typeof fallback === 'string' && fallback.trim() !== '') return fallback;
  return GENERIC_ERROR_MESSAGE[resolveErrorLocale(locale)];
}

/**
 * EmptyState headline for codes that have one (see `ERROR_TITLES`); `null`
 * when the code carries no title (the caller keeps its own generic title).
 */
export function errorCodeTitle(
  code: string | null | undefined,
  locale?: PhlixErrorLocale | null,
): string | null {
  if (!isRegisteredErrorCode(code)) return null;
  const titles = ERROR_TITLES[resolveErrorLocale(locale)];
  const localized = titles[code];
  if (typeof localized === 'string' && localized !== '') return localized;
  const english = ERROR_TITLES.en[code];
  if (typeof english === 'string' && english !== '') return english;
  return null;
}
